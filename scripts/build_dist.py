from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MODULES = {
    "core.Theme": "core/Theme.luau",
    "core.Animations": "core/Animations.luau",
    "core.Utils": "core/Utils.luau",
    "components.Elements": "components/Elements.luau",
    "components.Tab": "components/Tab.luau",
    "components.Window": "components/Window.luau",
    "components.Context": "components/Context.luau",
    "init": "init.luau",
}
REQUIRES = {
    "init.luau": {
        "require(script.components.Window)": 'requireModule("components.Window")',
        "require(script.components.Context)": 'requireModule("components.Context")',
        "require(script.core.Theme)": 'requireModule("core.Theme")',
        "require(script.core.Animations)": 'requireModule("core.Animations")',
    },
    "components/Context.luau": {
        "require(script.Parent.Parent.core.Theme)": 'requireModule("core.Theme")',
        "require(script.Parent.Parent.core.Animations)": 'requireModule("core.Animations")',
        "require(script.Parent.Parent.core.Utils)": 'requireModule("core.Utils")',
        "require(script.Parent.Window)": 'requireModule("components.Window")',
    },
    "components/Window.luau": {
        "require(script.Parent.Parent.core.Theme)": 'requireModule("core.Theme")',
        "require(script.Parent.Parent.core.Animations)": 'requireModule("core.Animations")',
        "require(script.Parent.Parent.core.Utils)": 'requireModule("core.Utils")',
        "require(script.Parent.Tab)": 'requireModule("components.Tab")',
    },
    "components/Tab.luau": {
        "require(script.Parent.Parent.core.Theme)": 'requireModule("core.Theme")',
        "require(script.Parent.Parent.core.Animations)": 'requireModule("core.Animations")',
        "require(script.Parent.Elements)": 'requireModule("components.Elements")',
    },
    "components/Elements.luau": {
        "require(script.Parent.Parent.core.Theme)": 'requireModule("core.Theme")',
        "require(script.Parent.Parent.core.Animations)": 'requireModule("core.Animations")',
    },
}


def build() -> str:
    output = [
        "-- Generated by scripts/build_dist.py. Do not edit this file directly.",
        "local moduleFactories = {}",
        "",
    ]

    for module_name, relative_path in MODULES.items():
        source = (ROOT / relative_path).read_text(encoding="utf-8")
        for old, new in REQUIRES.get(relative_path, {}).items():
            if old not in source:
                raise ValueError(f"Expected require not found in {relative_path}: {old}")
            source = source.replace(old, new)
        if "require(script" in source:
            raise ValueError(f"Unbundled ModuleScript require remains in {relative_path}")

        output.extend(
            [
                f'moduleFactories["{module_name}"] = function(requireModule)',
                source.rstrip(),
                "end",
                "",
            ]
        )

    output.extend(
        [
            "local moduleCache = {}",
            "",
            "local function requireModule(moduleName)",
            "    if moduleCache[moduleName] ~= nil then",
            "        return moduleCache[moduleName]",
            "    end",
            "",
            "    local factory = moduleFactories[moduleName]",
            "    if not factory then",
            '        error("Unknown bundled module: " .. tostring(moduleName), 2)',
            "    end",
            "",
            "    local result = factory(requireModule)",
            "    moduleCache[moduleName] = result",
            "    return result",
            "end",
            "",
            'return requireModule("init")',
            "",
        ]
    )
    return "\n".join(output)


if __name__ == "__main__":
    destination = ROOT / "dist/lowsime.luau"
    destination.write_text(build(), encoding="utf-8")
    print(f"Built {destination.relative_to(ROOT)}")
